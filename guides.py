# ═══════════════════════════════════════════════════════════════
#  匹配器（文档 5.2，精确匹配不区分大小写）
# ═══════════════════════════════════════════════════════════════

def match_guide(input_str: str) -> Optional[str]:
    """精确匹配图鉴名称或别名，返回 key 或 None"""
    clean = input_str.strip().lower()
    for key, val in GUIDE_REGISTRY.items():
        if clean == val["name"].lower():
            return key
        for alias in val.get("aliases", []):
            if clean == alias.lower():
                return key
    return None


# ═══════════════════════════════════════════════════════════════
#  列表生成器（文档 5.3）
# ═══════════════════════════════════════════════════════════════

def generate_guide_list(max_aliases: int = 3) -> str:
    """按分类生成图鉴列表"""
    total = len(GUIDE_REGISTRY)
    lines = [f"📋 心镜可用图鉴列表（{total}个）", ""]

    for category in CATEGORY_ORDER:
        items = [g for g in GUIDE_REGISTRY.values() if g["category"] == category]
        lines.append(f"{CATEGORY_ICONS[category]} {category}（{len(items)}个）")

        for item in items:
            aliases = item.get("aliases", [])[:max_aliases]
            alias_str = " / ".join(aliases) if aliases else ""
            lines.append(f"  {item['name']} → {alias_str}" if alias_str else f"  {item['name']}")

        lines.append("")

    lines.append("─────────────────────────")
    lines.append("💡 输入 /心镜 [名称] 直接开启对应图鉴（不区分大小写）")
    lines.append("   例如：/心镜 mbti、/心镜 攻受、/心镜 班味")

    return "\n".join(lines)
